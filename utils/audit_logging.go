const auditRequestIDKey = "okuru.audit.request_id"
const auditCountryCacheKey = "okuru.audit.country"
const auditDownloadCookieKey = "okuru.audit.download_cookie"

type auditCountryCache struct {
	ip, code, name, status string
}

// AuditJSONFormatter writes a readable severity and optional action marker
// followed by a structured JSON payload with a precise UTC timestamp.
type AuditJSONFormatter struct {
	formatter log.JSONFormatter
}

func NewAuditJSONFormatter() *AuditJSONFormatter {
	return &AuditJSONFormatter{formatter: log.JSONFormatter{TimestampFormat: time.RFC3339Nano}}
}

func (f *AuditJSONFormatter) Format(entry *log.Entry) ([]byte, error) {
	copy := *entry
	copy.Time = entry.Time.UTC()
	message, err := f.formatter.Format(&copy)
	if err != nil {
		return nil, err
	}
	label := strings.ToUpper(entry.Level.String())
	if entry.Level == log.FatalLevel || entry.Level == log.PanicLevel {
		label = "ERROR"
	}
	// Successful user actions are prominent without repeating INFO. Warnings
	// and errors keep their severity and retain the user_action category.
	if entry.Level == log.InfoLevel && entry.Data["category"] == "user_action" {
		label = "ACTION"
	}
	if entry.Data["category"] == "security" && (entry.Level == log.WarnLevel || entry.Level == log.ErrorLevel || entry.Level == log.FatalLevel || entry.Level == log.PanicLevel) {
		label = "SECURITY"
	}
	if label == "ACTION" || label == "SECURITY" || label == "ERROR" {
		message = prioritizeAuditMessage(message)
	}
	return append([]byte("["+label+"] "), message...), nil
}

// prioritizeAuditMessage moves the top-level message field without re-encoding
// any values. Logrus retains responsibility for escaping and field collisions.
// If the formatter output cannot be parsed, keep the original record intact.
func prioritizeAuditMessage(record []byte) []byte {
	decoder := json.NewDecoder(bytes.NewReader(record))
	open, err := decoder.Token()
	if err != nil || open != json.Delim('{') {
		return record
	}
	var message, others []byte
	for decoder.More() {
		start := decoder.InputOffset()
		key, err := decoder.Token()
		if err != nil {
			return record
		}
		var value json.RawMessage
		if err := decoder.Decode(&value); err != nil {
			return record
		}
		end := decoder.InputOffset()
		field := bytes.TrimSpace(record[start:end])
		field = bytes.TrimSpace(bytes.TrimPrefix(field, []byte(",")))
		if key == "msg" {
			if message != nil {
				return record
			}
			message = field
			continue
		}
		if len(others) != 0 {
			others = append(others, ',')
		}
		others = append(others, field...)
	}
	close, err := decoder.Token()
	if err != nil || close != json.Delim('}') || message == nil {
		return record
	}
	ordered := []byte{'{'}
	ordered = append(ordered, message...)
	if len(others) != 0 {
		ordered = append(ordered, ',')
		ordered = append(ordered, others...)
	}
	ordered = append(ordered, '}')
	return append(ordered, record[decoder.InputOffset():]...)
}

// SecurityAlert records a bounded, non-secret observation. Detection is
// advisory: neither an unusual request nor a traffic threshold proves abuse.
// Callers must supply only bounded fields derived from trusted constants or
// numeric counters, never raw URLs, credentials, headers or request bodies.
func SecurityAlert(c *echo.Context, event, message string, fields log.Fields) {
	data := make(log.Fields, len(fields)+8)
	for name, value := range fields {
		data[name] = value
	}
	for _, name := range []string{"request_id", "client_ip", "peer_ip", "client_ip_source", "client_country_code", "client_country_name", "client_country_status", "method", "route"} {
		delete(data, name)
	}
	for name, value := range AuditRequestFields(c) {
		data[name] = value
	}
	if c == nil {
		delete(data, "request_id")
	}
	data["category"] = "security"
	data["event"] = event
	log.WithFields(data).Warn(message)
}

// AuditRequestID is generated by the server and never taken from a client header.
// A context is scoped to one request; subsequent calls reuse its identifier.
func AuditRequestID(c *echo.Context) string {
	if c == nil {
		return ""
	}
	if id, ok := c.Get(auditRequestIDKey).(string); ok {
		return id
	}
	id, err := uuid.NewRandom()
	if err != nil {
		return ""
	}
	value := id.String()
	c.Set(auditRequestIDKey, value)
	return value
}

// RecordDownloadCookieCheck records only the outcome of the path-specific
// cookie lookup. A digest match still requires a live session in Redis.
func RecordDownloadCookieCheck(c *echo.Context, present, matched bool) {
	state := "missing"
	if matched {
		state = "matched"
	} else if present {
		state = "mismatch"
	}
	c.Set(auditDownloadCookieKey, state)
}

// AuditRequestFields contains bounded, non-secret request metadata only.
// Proxy-supplied addresses are used only after the existing trust checks.
func AuditRequestFields(c *echo.Context) log.Fields {
	fields := log.Fields{"request_id": AuditRequestID(c)}
	if c == nil || c.Request() == nil {
		fields["client_ip_source"] = "unavailable"
		fields["client_country_status"] = GeoIPAddressUnavailable
		fields["route"] = "unmatched"
		return fields
	}
	address, _ := ResolveClientAddress(c.Request())
	fields["client_ip_source"] = address.Source
	if address.ClientIP != "" {
		fields["client_ip"] = address.ClientIP
		country, ok := c.Get(auditCountryCacheKey).(auditCountryCache)
		if !ok || country.ip != address.ClientIP {
			country = auditCountryCache{ip: address.ClientIP}
			country.code, country.name, country.status = LookupGeoIPCountry(address.ClientIP)
			c.Set(auditCountryCacheKey, country)
		}
		fields["client_country_status"] = country.status
		if country.code != "" {
			fields["client_country_code"] = country.code
		}
		if country.name != "" {
			fields["client_country_name"] = country.name
		}
	} else {
		fields["client_country_status"] = GeoIPAddressUnavailable
	}
	if address.PeerIP != "" {
		fields["peer_ip"] = address.PeerIP
	}
	fields["method"] = auditRequestMethod(c.Request().Method)
	route := c.Path()
	if route == "" {
		route = "unmatched"
	}
	fields["route"] = boundedAuditText(route, 256)
	if route == "/file/:file_key/download/:session_id" {
		fields["download_range_present"] = c.Request().Header.Get("Range") != ""
		fields["download_if_range_present"] = c.Request().Header.Get("If-Range") != ""
		if cookie, ok := c.Get(auditDownloadCookieKey).(string); ok {
			fields["download_cookie"] = cookie
		}
	}
	return fields
}

// Method tokens are supplied by clients and can themselves contain sensitive
// data. Keep only standard method names in audit records.
func auditRequestMethod(method string) string {
	switch method {
	case http.MethodGet, http.MethodHead, http.MethodPost, http.MethodPut,
		http.MethodDelete, http.MethodConnect, http.MethodOptions, http.MethodTrace, http.MethodPatch:
		return method
	default:
		return "OTHER"
	}
}

// AuditEvent records successful application events without resource tokens,
// filenames, contents, credentials or concrete request URLs.
func AuditEvent(c *echo.Context, event, message string) {
	log.WithFields(AuditRequestFields(c)).WithFields(log.Fields{
		"category": "user_action", "event": event, "outcome": "success",
	}).Info(message)
}

// AuditAlert records an operation failure without logging its raw error or input.
func AuditAlert(c *echo.Context, event, message string) {
	log.WithFields(AuditRequestFields(c)).WithFields(log.Fields{
		"category": "user_action", "event": event, "outcome": "failure",
	}).Warn(message)
}

func boundedAuditText(value string, limit int) string {
	var out strings.Builder
	for len(value) > 0 {
		r, size := utf8.DecodeRuneInString(value)
		if out.Len()+utf8.RuneLen(r) > limit {
			break
		}
		out.WriteRune(r)
		value = value[size:]
	}
	return out.String()
}

// AuditError records an operational failure without exposing request data.
func AuditError(c *echo.Context, event, message string) {
	log.WithFields(AuditRequestFields(c)).WithFields(log.Fields{
		"category": "user_action", "event": event, "outcome": "failure",
	}).Error(message)
}

// AuditStarted records an operation that has begun without claiming completion.
func AuditStarted(c *echo.Context, event, message string) {
	log.WithFields(AuditRequestFields(c)).WithFields(log.Fields{
		"category": "user_action", "event": event, "outcome": "started",
	}).Info(message)
}
